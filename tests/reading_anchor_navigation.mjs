import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const classes=new Set();let row=null;
let held=false;const frames=[];const positions=[];
const nav={setAttribute(){held=true},removeAttribute(){held=false},offsetHeight:112,classList:{contains:x=>classes.has(x),add:x=>classes.add(x),toggle(x,on){on?classes.add(x):classes.delete(x)}}};
const ctx={innerWidth:1456,innerHeight:900,scrollY:0,document:{documentElement:{scrollHeight:10000},querySelector:s=>s==='.site-nav'?nav:row},getComputedStyle:e=>e.style||{getPropertyValue:()=>112},requestAnimationFrame:f=>frames.push(f),scrollTo:p=>positions.push(p.top)};
