// WIKI_BASE_URL=http://127.0.0.1:8795 PLAYWRIGHT_MODULE=/path/to/playwright node tests/engineering_opening_browser.cjs
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const out=process.env.ENGINEERING_OUTPUT || 'work/engineering-opening-browser';
 fs.mkdirSync(out,{recursive:true});
 const base=process.env.WIKI_BASE_URL || 'http://127.0.0.1:8795';
 const errors=[];
 async function page(options={}) { const p=await browser.newPage({viewport:{width:1440,height:900},...options});p.setDefaultTimeout(8000); p.on('pageerror',e=>errors.push(e.message)); return p; }
 const p=await page();

 await p.goto(`${base}/engineering`,{waitUntil:'domcontentloaded'});
 await p.waitForSelector('[data-opening="playing"]');
 assert.equal(await p.locator('html').getAttribute('data-entry-loading'),null);
 assert.equal(await p.locator('[data-dbtl-wheel]').count(),1);
 assert.equal(await p.locator('[data-dbtl-stage]').count(),4);
 assert.equal(await p.locator('[data-opening-dbtl]').count(),1);
 const geometry=await p.locator('.dbtl-wheel__rim').evaluateAll(els=>els.map(el=>el.getAttribute('d')));
 assert.equal(geometry.length,2);assert.equal(geometry[0],geometry[1]);
 const ids=await p.locator('[id]').evaluateAll(els=>els.map(e=>e.id));assert.equal(ids.length,new Set(ids).size);
 await p.waitForTimeout(5200);
 assert.equal(await p.locator('[data-engineering-workspace]').getAttribute('data-opening'),'playing','Cover waits indefinitely');
 await p.mouse.wheel(0,700);await p.waitForTimeout(350);
 assert.equal(await p.locator('[data-engineering-workspace]').getAttribute('data-opening'),'playing','Scrolling does not enter');
 await p.screenshot({path:`${out}/desktop-opening.png`});
 await p.locator('.engineering-opening__title').click();
 await p.waitForSelector('[data-engineering-workspace]:not([data-opening])');
 assert.equal(await p.locator('[data-engineering-map]').getAttribute('inert'),null);
 await p.screenshot({path:`${out}/desktop-map.png`});
 await p.getByRole('button',{name:'Replay opening animation'}).click();
 await p.waitForSelector('[data-opening="playing"]');
 await p.getByRole('button',{name:'Tap anywhere to explore'}).focus();
 await p.keyboard.press('Enter');
 await p.waitForSelector('[data-engineering-workspace]:not([data-opening])');
 await p.getByRole('link',{name:'Start engineering',exact:true}).click();
 await p.waitForSelector('[data-engineering-view="reader"]');
 await p.locator('[data-dbtl-stage="build"]').click();
 assert.match(p.url(),/#fundamental-research-cycle-01-build/);
 await p.locator('[data-engineering-map-back]').click();
 await p.getByRole('button',{name:'Switch to mind map'}).click();
 await p.waitForSelector('[data-overview-section="mindmap"]');
 assert.equal(await p.getByRole('button',{name:'Replay opening animation'}).isVisible(),false);
 await p.goto(`${base}/engineering#pod`,{waitUntil:'domcontentloaded'});
 await p.waitForSelector('[data-engineering-view="reader"]');
 assert.equal(await p.locator('[data-engineering-workspace]').getAttribute('data-opening'),null);
 const mobile=await page({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.goto(`${base}/engineering`,{waitUntil:'domcontentloaded'});
 await mobile.waitForSelector('[data-opening="playing"]');await mobile.waitForTimeout(1700);
 await mobile.screenshot({path:`${out}/mobile-opening.png`});
 const boxes=await mobile.locator('.engineering-opening__title,.engineering-opening__blueprint,.engineering-opening__foot,.engineering-opening__enter').evaluateAll(els=>els.map(e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom};}));
 assert.ok(boxes.every(r=>r.x>=0 && r.right<=390 && r.y>=0 && r.bottom<=844),'Opening fits mobile viewport');
 await mobile.getByRole('button',{name:'Tap anywhere to explore'}).tap();
 await mobile.waitForSelector('[data-engineering-workspace]:not([data-opening])');
 const reduced=await page({reducedMotion:'reduce'});
 await reduced.goto(`${base}/engineering`,{waitUntil:'domcontentloaded'});
 await reduced.waitForSelector('[data-opening="playing"]');
 const animations=await reduced.locator('[data-engineering-opening]').evaluate(el=>el.getAnimations({subtree:true}).length);
 assert.equal(animations,0,'Reduced motion retains a static tap-to-enter cover');
 await reduced.getByRole('button',{name:'Tap anywhere to explore'}).click();
 assert.equal(await reduced.locator('[data-engineering-workspace]').getAttribute('data-opening'),null);
 const nojs=await page({javaScriptEnabled:false});await nojs.goto(`${base}/engineering`);
 assert.equal(await nojs.locator('[data-engineering-opening]').isVisible(),false);
 assert.equal(await nojs.locator('.engineering-paper').isVisible(),true);
 assert.deepEqual(errors,[]);
 fs.writeFileSync(`${out}/report.json`,JSON.stringify({passed:['indefinite cover hold','scroll does not enter','tap anywhere to enter','shared DBTL geometry','unique SVG IDs and reader controls','replay','keyboard enter','original reader DBTL navigation','mind map switch','direct chapter link','mobile tap and bounds','static reduced-motion cover','JavaScript disabled fallback'],errors},null,2));
 console.log('PASS: persistent cover, tap/keyboard entry, shared DBTL, reading controls, mobile, reduced motion and no-JS fallback; no page errors.');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
