"""Bake the curved cup lettering into three lightweight SVG paths.

The cached, font-free glyph contours make ordinary regeneration stdlib-only.
Refresh contours with extract_hp_cup_glyphs.py only when changing the lettering.
"""
import json
from math import sin, cos, radians, ceil, hypot
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WIDTH = 270

def project(u, v):
    theta = (u / WIDTH * 2 - 1) * 1.05
    bow = (cos(theta) - cos(1.05)) / (1 - cos(1.05))
    x = 567 + (136 - .09 * v) * sin(theta) / sin(1.05)
    y = 520 + .76 * v + (28 + .07 * v) * bow
    angle = radians(1.5)
    dx, dy = x - 567, y - 589
    return (567 + dx * cos(angle) - dy * sin(angle),
            589 + dx * sin(angle) + dy * cos(angle))

def clip_edge(points, axis, limit, greater):
    if not points: return []
    result=[]
    previous=points[-1]
    inside=lambda p: p[axis]>=limit if greater else p[axis]<=limit
    for point in points:
        before,after=inside(previous),inside(point)
        if before != after:
            t=(limit-previous[axis])/(point[axis]-previous[axis])
            result.append(tuple(previous[k]+t*(point[k]-previous[k]) for k in (0,1)))
        if after: result.append(point)
        previous=point
    return result

def clipped(points, y0, height):
    for axis,limit,greater in [(0,-1,True),(0,271,False),(1,y0,True),(1,y0+height,False)]:
        points=clip_edge(points,axis,limit,greater)
    return points

def warped_path(points):
    # Densify straight segments too: the cup bends horizontal letter strokes.
    dense=[]
    for a,b in zip(points,points[1:]+points[:1]):
        steps=max(1,ceil(hypot(b[0]-a[0],b[1]-a[1])/2))
        for i in range(steps):
            t=i/steps
            dense.append(project(a[0]+t*(b[0]-a[0]),a[1]+t*(b[1]-a[1])))
    if len(dense)<3: return ''
    return 'M'+'L'.join(f'{x:.2f},{y:.2f}' for x,y in dense)+'Z'

outlines=json.loads((ROOT/'docs/design/hp-opening/this-glyph-outlines.json').read_text())['contours']
parts=['{# Generated by scripts/build_hp_cup_projection.py; three baked paths, no runtime mesh or glyph clipping. #}', '<g class="hp-cup-print" aria-hidden="true">']
for name,y,height,baseline in [('top',0,27,74),('middle',32,35,86),('bottom',76,58,121)]:
    path=''.join(warped_path(clipped([(x,py+baseline) for x,py in contour],y,height)) for contour in outlines)
    assert path and 'nan' not in path.lower()
    parts.append(f'<g class="hp-cup-wrap-row hp-cup-wrap-row--{name}"><path class="hp-cup-ink hp-cup-ink--{name}" d="{path}"/></g>')
parts.append('</g>')
output=ROOT/'wiki/components/human-practices/cup_print.html'
output.write_text('\n'.join(parts)+'\n')
print(f'Built 3 baked SVG paths, 0 mesh uses, 0 glyph clip paths ({output.stat().st_size:,} bytes).')
