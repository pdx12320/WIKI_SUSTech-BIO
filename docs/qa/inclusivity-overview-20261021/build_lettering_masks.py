"""Derive tight SVG masks from the supplied lettering; artwork stays unchanged."""
from pathlib import Path
import json
from PIL import Image, ImageFilter
import numpy as np
root=Path(__file__).resolve().parents[3]
source=np.array(Image.open(root/'assets/human-practices/inclusivity-overview/inclusivity-hand-drawn-overview-20261021.jpg').convert('RGB'))
labels=[
 ('Healthy child learning',296,76,195,76),
 ('Needing vision support',807,19,282,50),
 ('Clear vision',168,426,171,50),
 ('Doctor and family caregiver',366,369,361,56),
 ('Living with AD and shared lived experience',883,246,320,92),
 ('Our needs change throughout life',113,517,651,65),
 ('Our right to be heard, to choose, and to participate does not',111,578,1131,78),
]
records=[]
for name,x,y,w,h in labels:
 mask=np.zeros(source.shape[:2],dtype=np.uint8)
 mask[y:y+h,x:x+w]=(source[y:y+h,x:x+w].max(axis=2)<170)*255
 mask=np.array(Image.fromarray(mask).filter(ImageFilter.MaxFilter(5)))>0
 # Merge identical horizontal runs across adjacent rows into compact rectangles.
 active={};rectangles=[]
 for row in range(mask.shape[0]+1):
  runs=[]
  if row<mask.shape[0]:
   edges=np.diff(np.r_[False,mask[row],False].astype(np.int8))
   runs=list(zip(np.where(edges==1)[0],np.where(edges==-1)[0]))
  current=set(runs)
  for run,start in list(active.items()):
   if run not in current:
    rectangles.append((int(run[0]),start,int(run[1]-run[0]),row-start));del active[run]
  for run in runs:active.setdefault(run,row)
 d=''.join(f'M{rx} {ry}h{rw}v{rh}h{-rw}Z' for rx,ry,rw,rh in rectangles)
 records.append({'name':name,'region':{'x':x-3,'y':y-3,'width':w+6,'height':h+6},'d':d,'maskPixels':int(mask.sum())})
out=root/'static/human-practices/inclusivity-overview/lettering.mjs'
out.write_text('// Tight masks of the supplied original lettering, generated by the QA helper.\nexport const lettering = '+json.dumps(records,separators=(',',':'))+';\n')
print(json.dumps({'letter_groups':len(records),'svg_bytes':out.stat().st_size,'mask_pixels':[r['maskPixels'] for r in records]},indent=2))
