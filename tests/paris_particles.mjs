import assert from 'node:assert/strict';
import * as THREE from '../static/vendor/three/three.module.js';
import { CITY_DOTS, TOWER_POINTS, FAR_CITY_DOTS } from '../static/onetake/paris-tower-shape.mjs';
import { createParisParticles, particlePhase } from '../static/onetake/paris-particles.mjs';
globalThis.innerWidth = 1280; globalThis.innerHeight = 800; globalThis.devicePixelRatio = 1;
let staticMode = false;
const root = { querySelector: () => true, classList: { add() {}, contains: () => staticMode } };
const scene = new THREE.Scene();
const sourceGeometry = new THREE.BufferGeometry();
sourceGeometry.setAttribute('position', new THREE.BufferAttribute(new Float32Array(3200*3), 3));
const source = new THREE.Points(sourceGeometry, new THREE.ShaderMaterial({uniforms:{uParisMorph:{value:0},uOpacity:{value:.85},uSize:{value:2.1}}}));
source.name = 'extracellular-amyloid'; scene.add(source);
const sourceIdentity = source.uuid;
const field = createParisParticles(THREE, scene, root, new THREE.Vector3(-1.2,1.6,15), new THREE.Vector3());
const points = scene.getObjectByName('paris-population-world-particles');
const geometry = points.geometry;
assert.equal(geometry.attributes.position.count, 26 * FAR_CITY_DOTS);
assert.equal(new Set(geometry.attributes.aCity.array).size, 26);
const depths = Array.from(geometry.attributes.position.array).filter((_, i) => i % 3 === 2);
assert.ok(Math.max(...depths) - Math.min(...depths) > .8, 'groups occupy staggered depths');
assert.equal(scene.getObjectByName('extracellular-amyloid').uuid, sourceIdentity);
assert.equal(source.geometry.attributes.position.count, 3200, 'original Aβ vertex count retained');
assert.equal(source.geometry.attributes.aParis.count, 3200, 'each original vertex has a tower destination');
assert.ok(CITY_DOTS >= 1500 && CITY_DOTS <= 1800);
assert.ok(FAR_CITY_DOTS<=400,'wide view uses an efficient detail level');
assert.ok(Math.max(...TOWER_POINTS.map(p=>p[2]))>.22 && Math.min(...TOWER_POINTS.map(p=>p[2]))<-.22,'four legs occupy front and back depths');
assert.ok(Math.max(...TOWER_POINTS.map(p=>p[1])) > .6, 'tower has a spire');
assert.ok(Math.min(...TOWER_POINTS.map(p=>p[0])) < -.22 && Math.max(...TOWER_POINTS.map(p=>p[0])) > .22, 'tower has flared feet');
const closePosition = new THREE.Vector3(), closeLook = new THREE.Vector3();
const farPosition = new THREE.Vector3(), farLook = new THREE.Vector3();
field.camera(.754, closePosition, closeLook);
field.camera(.775, farPosition, farLook);
assert.ok(farPosition.distanceTo(points.parent.position) > closePosition.distanceTo(points.parent.position)*6, 'camera retreat shrinks the original large tower into one of 27');
const projectedTower = (width,height) => {
  innerWidth=width;innerHeight=height;
  const pos=new THREE.Vector3(),look=new THREE.Vector3();
  field.camera(.754,pos,look);
  const camera=new THREE.PerspectiveCamera(38,width/height,.1,200);
  camera.position.copy(pos);camera.lookAt(look);camera.updateMatrixWorld();
  const attr=source.geometry.attributes.aParis;
  const vertices=Array.from({length:attr.count},(_,i)=>new THREE.Vector3().fromBufferAttribute(attr,i).project(camera));
  return {height:(Math.max(...vertices.map(p=>p.y))-Math.min(...vertices.map(p=>p.y)))/2,
    top:Math.max(...vertices.map(p=>p.y)),bottom:Math.min(...vertices.map(p=>p.y))};
};
const desktopTower=projectedTower(1280,800);
assert.ok(desktopTower.height>.69&&desktopTower.height<.76,'single desktop tower fills about 72% of viewport height');
assert.ok(desktopTower.top<.75, 'large tower clears the desktop navigation');
const mobileTower=projectedTower(390,844);
assert.ok(mobileTower.height>.51&&mobileTower.height<.58,'single mobile tower fills over half the viewport height');
assert.ok(mobileTower.top<1&&mobileTower.bottom>-1,'mobile tower remains fully in view');
innerWidth=1280;innerHeight=800;
field.camera(.754,new THREE.Vector3(),new THREE.Vector3());
const midPosition=new THREE.Vector3(),midLook=new THREE.Vector3();
field.camera(.7645,midPosition,midLook);
const geometricMiddle=Math.sqrt(closePosition.distanceTo(points.parent.position)*farPosition.distanceTo(points.parent.position));
assert.ok(Math.abs(midPosition.distanceTo(points.parent.position)/geometricMiddle-1)<.05,'camera retreats at an even perceived scale');
assert.equal(particlePhase(.754).zoom, 0);
assert.equal(particlePhase(.754).cities, 1);
assert.equal(particlePhase(.775).zoom, 1);
assert.equal(particlePhase(.775).cities, 27);
field.update(.768, 1);
assert.equal(points.parent.visible, true);
const anchor = points.parent.position.clone();
field.update(.777, 2);
assert.deepEqual(points.parent.position, anchor, 'world anchor stays fixed while take and camera advance');
scene.updateMatrixWorld(true);
const p = new THREE.Vector3().applyMatrix4(points.matrixWorld);
const a = new THREE.PerspectiveCamera(38, 1.6, .1, 200);
a.position.set(-1,1.6,15); a.lookAt(0,0,0); a.updateMatrixWorld();
const first = p.clone().project(a);
a.position.x -= 2; a.lookAt(-1,0,0); a.updateMatrixWorld();
assert.ok(first.distanceTo(p.clone().project(a)) > .05, 'main camera produces visible parallax');
field.update(.82, 3); assert.equal(points.parent.visible, false);
staticMode = true; field.update(.765, 4); assert.equal(points.parent.visible, false);
staticMode = false;
innerWidth = 390; innerHeight = 844; field.update(.765, 4);
assert.ok(Number.isFinite(points.parent.position.x));
assert.ok(points.parent.scale.x < 1, 'portrait field fits the available width');
for (const t of [.7,.736,.748,.765,.78,.80,.82]) {
  const expected = particlePhase(t); field.update(.82,4); field.update(t,4);
  assert.equal(source.material.uniforms.uParisMorph.value, expected.form);
  assert.equal(points.material.uniforms.uDepart.value, expected.depart);
  assert.ok(expected.opacity >= 0 && expected.opacity <= 1);
}
// Biology resets source opacity before each population update in the live frame.
const observed = take => {
  source.material.uniforms.uOpacity.value = .85 * particlePhase(take).backdrop;
  field.update(take, 2);
  return [source.material.uniforms.uOpacity.value, source.material.uniforms.uParisMorph.value];
};
for(const take of [.73,.742,.748,.755,.773,.80,.82]) {
  const expected = observed(take); observed(.82); observed(.73);
  assert.deepEqual(observed(take), expected, 'Aβ morph and density normalization reverse deterministically');
}
assert.equal(particlePhase(.7).backdrop, 1);
assert.equal(particlePhase(.82).backdrop, 1);
const isolated = new THREE.Scene();
const noop = createParisParticles(THREE, isolated, {querySelector:()=>null});
noop.update(.765, 1); assert.equal(noop.backdrop(.765), 1);
assert.equal(isolated.children.length, 0, '/next keeps its existing scene');
console.log('Passed original Aβ identity/count, tower destinations, single-city hold, camera pullback, 27-city reveal, depth, fallback and /next isolation');
