"""Generate SAP's hosting adapter from every confirmed SAP upload.

Run after updating asset_mapping.csv. --check detects stale release adapters.
The adapter lives outside the sealed SAP package and does not alter its data.
"""
import argparse
import csv
import json
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
PREFIX = 'static/sap-demo/'


def render(mapping_file):
    mapping = {}
    with Path(mapping_file).open(encoding='utf-8-sig', newline='') as stream:
        for row in csv.DictReader(stream):
            name = row['local_path']
            if row['match_status'] != 'matched' or not name.startswith(PREFIX):
                continue
            target = row['igem_url']
            parsed = urlsplit(target)
            if parsed.scheme != 'https' or parsed.netloc != 'static.igem.wiki':
                raise ValueError(f'Invalid official upload: {name}')
            key = name[len(PREFIX):]
            if key in mapping and mapping[key] != target:
                raise ValueError(f'Conflicting upload: {name}')
            mapping[key] = target
    if 'data/overview.json' not in mapping:
        raise ValueError('Missing confirmed SAP overview upload')
    template = '''/* Generated by scripts/build_sap_cdn_adapter.py; scientific data are unchanged. */
(() => {
  const nativeFetch = window.fetch.bind(window);
  const root = new URL('./', document.baseURI);
  const mapping = MAPPING;
  const uploadedURL = input => {
    const url = new URL(input instanceof Request ? input.url : input, document.baseURI);
    const relative = url.origin === root.origin && url.pathname.startsWith(root.pathname)
      ? decodeURIComponent(url.pathname.slice(root.pathname.length)) : '';
    return mapping[relative];
  };
  window.fetch = (input, options) => {
    const target = uploadedURL(input);
    if (!target) return nativeFetch(input, options);
    // Preserve Request method, headers and other caller options if one is supplied.
    return nativeFetch(input instanceof Request ? new Request(target, input) : target, options);
  };
  // SAP also inserts download links when its construction view is rendered.
  document.addEventListener('DOMContentLoaded', () => {
    const rewriteLinks = () => document.querySelectorAll('a[href]').forEach(link => {
      const target = uploadedURL(link.href);
      if (target) link.href = target;
    });
    rewriteLinks();
    new MutationObserver(rewriteLinks).observe(document.body, {childList: true, subtree: true});
  });
})();
'''
    return template.replace('MAPPING', json.dumps(dict(sorted(mapping.items())), indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mapping', type=Path, default=ROOT / 'asset_mapping.csv')
    parser.add_argument('--output', type=Path, default=ROOT / 'static/sap-demo-cdn.js')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(args.mapping)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != expected:
            raise SystemExit('SAP CDN adapter is stale. Run python scripts/build_sap_cdn_adapter.py')
        print('SAP CDN adapter covers all confirmed uploads.')
    else:
        args.output.write_text(expected)
        print(f'Updated {args.output}')


if __name__ == '__main__':
    main()
